## Get QRUNIDs for each field:
qrunid_c1 = set(data_c1['QRUNID'])
qrunid_c2 = set(data_c2['QRUNID'])

## QRUNIDs in common:
qrunid_both = sorted(qrunid_c1.intersection(qrunid_c2))


## Next, make lists of the images in common QRUNIDs:
c1_imlist = {}
c2_imlist = {}
for qrunid in qrunid_both:
    sys.stderr.write("qrunid: %s\n" % qrunid)
    c1_subset = data_c1[data_c1['QRUNID'] == qrunid]
    c2_subset = data_c2[data_c2['QRUNID'] == qrunid]
    c1_imlist[qrunid] = [x for x in c1_subset.imtag]
    c2_imlist[qrunid] = [x for x in c2_subset.imtag]
    # check MJD difference for close-in-time cases:
    c1_mjd = c1_subset['MJD-OBS'].values
    c2_mjd = c2_subset['MJD-OBS'].values
    # make matrix of mjd1 - mjd2:
    deltas = np.abs(c1_mjd[:, None] - c2_mjd)
    mindiff = deltas.min(axis=1)
    min_idx = deltas.argmin(axis=1)
    sys.stderr.write("Smallest time difference: %.4f days\n" % mindiff.min())


